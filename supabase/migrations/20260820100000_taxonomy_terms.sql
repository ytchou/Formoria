  'hand. Read by brands_search_document to expand stored slugs to zh-TW labels '
  'before tokenising.';

-- Grants mirror `subcategory_translations` (20260819090000:328-333): RLS on
-- with a read policy, but no anon/authenticated grant. Only `postgres` and
-- `service_role` write `public.brands` (checked live: those are the sole
-- INSERT/UPDATE grantees), so those are the only roles whose search-vector
-- trigger ever needs to read this table. Widening the grant would publish a
-- new PostgREST collection for no caller.
alter table public.taxonomy_terms enable row level security;
create policy taxonomy_terms_public_read
  on public.taxonomy_terms for select
  using (true);
revoke all on table public.taxonomy_terms from public, anon, authenticated;
grant all on table public.taxonomy_terms to postgres, service_role;

