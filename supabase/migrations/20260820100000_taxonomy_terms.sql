create table public.taxonomy_terms (
  axis text not null,
  slug text not null,
  name_zh text not null,
  name_en text not null,
  constraint taxonomy_terms_pkey primary key (axis, slug),
  constraint taxonomy_terms_axis_check check (axis in ('l1', 'l2', 'material')),
  constraint taxonomy_terms_slug_check check (slug <> ''),
  constraint taxonomy_terms_name_zh_check check (name_zh <> ''),
  constraint taxonomy_terms_name_en_check check (name_en <> '')
