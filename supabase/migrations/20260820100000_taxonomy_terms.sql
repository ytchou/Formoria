declare
  v_offenders text;
begin
  select string_agg(t.axis || ':' || t.slug, ', ' order by t.axis || ':' || t.slug)
  into v_offenders
  from public.taxonomy_terms as t
  where t.axis <> 'material'
    and t.name_zh = t.slug;

