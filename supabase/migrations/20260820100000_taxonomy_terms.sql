-- `taxonomy_terms` — the SQL-side mirror of src/lib/taxonomy/ontology.ts
-- (DEV-1510, Task 6).
--
-- WHY THE TABLE EXISTS
-- ---------------------------------------------------------------------------
--
-- DEV-1510 changes `brands.subcategories` from zh-TW labels to English slugs.
-- The moment it does, the `cjk_bigrams` weight-C arm of
-- `brands_search_document` (20260809100000_cjk_bigram_search.sql:107-113) has
-- no CJK text left to tokenise, and `後背包` stops matching a brand tagged
-- `backpacks`. Nothing asserts a ranking weight, so that loss is silent: the
-- slug filter keeps working, the row just disappears from search.
--
-- Task 7 rewrites the search functions to expand each stored slug back to its
-- `name_zh` before indexing. This table is what they expand through.
--
-- WHY IT IS GENERATED
-- ---------------------------------------------------------------------------
--
-- The seed block below is emitted by `scripts/generate-taxonomy-terms.ts`,
-- which IMPORTS the ontology module rather than parsing it. A hand-written
-- copy of a 200-term vocabulary drifts on the first rename, and a drifted row
-- is undetectable at runtime — the label simply stops being indexed. The parity
-- test (`src/lib/taxonomy/__tests__/taxonomy-terms-parity.test.ts`) compares
-- ontology to committed SQL, so it gates CI with no database.
--
-- The generator is deliberately not a regex. `scripts/model-ab/report.py:19`
-- reads `ontology.ts` with a Python regex and under-counts silently; the same
-- shape reports 172 of the 175 L2 nodes because three entries wrap onto extra
-- lines. Task 18 removes that regex for the same reason.
--
-- WHAT IT REPLACES, AND WHAT IT DOES NOT
-- ---------------------------------------------------------------------------
--
-- It replaces `subcategory_translations` (20260819090000:323-333), a
-- label-keyed cache the enrichment phase writes into. It does NOT replace
-- `product_tag_translations` — the DEV-1503 contract migration already dropped
-- that one (20260819090000:839).
--
-- `subcategory_translations` is NOT dropped here. The search trigger and
-- `canonicalize_subcategory_translations` still read it at this point in the
-- ledger; Task 7 (20260820110000_search_expands_slugs.sql) inverts both and
-- drops the table in the same transaction that stops reading it. Dropping it
-- one migration early would take the enrichment RPC down between deploys.
--
-- AXES
-- ---------------------------------------------------------------------------
--
--   l1        13 rows   slug = the L1 category slug
--   l2       175 rows   slug = the L2 subcategory slug (what `subcategories`
--                       stores after Task 9)
--   material  12 rows   slug = the zh-TW term itself, because that is what
--                       `brands.material` stores and what `?material=` carries
--
-- `crafts` and its 12 L2s are present on purpose. DEV-1507 retires them;
-- DEV-1510 does not.
--
-- Composite primary key on (axis, slug): an L1 slug and an L2 slug are drawn
-- from different namespaces and a future collision must not be a load error.

