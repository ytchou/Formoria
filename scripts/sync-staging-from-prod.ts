/**
 * The ONLY write in this file. Sequential by design: parallel batches against
 * the same conflict target deadlock each other, and a failure mid-flight would
 * leave a set of half-applied tables nobody can reason about.
 *
 * A failing batch fails the table. Continuing past one would report a copied
 * count that no longer describes what staging holds.
 */
async function upsertBatch(
  client: StagingClient,
  table: string,
  rows: Row[],
  onConflict: string,
  batchSize: number,
): Promise<number> {
  let written = 0;
  for (const batch of chunked(rows, batchSize)) {
    const { error } = await client.from(table).upsert(batch, { onConflict });
    if (error) {
      throw new Error(
        `upsert ${table} (${written}/${rows.length} written) failed: ${describeError(error)}`,
      );
    }
    written += batch.length;
  }
  return written;
}

