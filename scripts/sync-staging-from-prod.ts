type ApiKeyEntry = { id?: unknown; type?: unknown; api_key?: unknown };

/**
 * Fetches a project's legacy service_role key from the Supabase CLI.
 *
 * Never from the environment, for two reasons. `.env.local` holds PRODUCTION
 * under the generic `NEXT_PUBLIC_SUPABASE_URL` / `SUPABASE_SERVICE_ROLE_KEY`
 * names, so an environment-reading script would default to writing production.
 * And `scripts/check-service-registry.mjs`, which runs before lint on every CI
 * leg, hard-fails on any unregistered credential-shaped env var — a second
 * pair of names would have to be registered as a service this script does not
 * have.
 *
 * Only the legacy JWT form is accepted: it is the only key format that carries
 * a verifiable project ref, which is what makes the identity check below more
 * than a comment.
 */
export function resolveServiceRoleKey(ref: string): {
  url: string;
  key: string;
} {
  const result = spawnSync(
    "pnpm",
    [
      "exec",
      "supabase",
      "projects",
      "api-keys",
      "--project-ref",
      ref,
      "-o",
      "json",
    ],
    { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
  );
  if (result.status !== 0) {
    throw new Error(
      `supabase projects api-keys failed for ${ref}: ${result.stderr.trim() || "no output"}. Run \`pnpm exec supabase login\` first.`,
    );
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(result.stdout) as unknown;
  } catch {
    throw new Error(`supabase projects api-keys returned non-JSON for ${ref}`);
  }
  if (!Array.isArray(parsed)) {
    throw new Error(
      `supabase projects api-keys returned no key list for ${ref}`,
    );
  }

  const entry = (parsed as ApiKeyEntry[]).find(
    (candidate) =>
      isRecord(candidate) &&
      candidate.id === "service_role" &&
      candidate.type === "legacy",
  );
  const key = entry && typeof entry.api_key === "string" ? entry.api_key : "";
  if (!key) {
    throw new Error(`No legacy service_role key found for project ${ref}`);
  }

  validateSupabaseKeyIdentity(key, `service_role@${ref}`, ref, "service_role");
  return { url: `https://${ref}.supabase.co`, key };
}

/**
 * The production handle. Write-blocked, so a stray write cannot reach Postgres
 * even if a future edit adds one; the blocked tally is checked at exit.
 */
function createProductionClient(): {
  client: ProdClient;
  blocked: BlockedWrite[];
  url: string;
  key: string;
} {
  const { url, key } = resolveServiceRoleKey(PRODUCTION_PROJECT_REF);
  const ref = projectRefFromSupabaseUrl(url);
  if (ref !== PRODUCTION_PROJECT_REF) {
    throw new Error(`Production URL identifies project ${ref}`);
  }
  const { client, blocked } = createWriteBlockingClient(url, key);
  return { client: client as ProdClient, blocked, url, key };
}

/**
 * The staging handle. Under `--dry-run` it is wrapped in the same write
 * blocker as production — the opposite direction, the same primitive. A dry
 * run then cannot leak a write no matter which branch it takes, and the
 * blocked tally doubles as the "what would have been written" report.
 */
function createStagingClient(dryRun: boolean): {
  client: StagingClient;
  blocked: BlockedWrite[];
  url: string;
  key: string;
} {
  const { url, key } = resolveServiceRoleKey(STAGING_PROJECT_REF);
  const ref = projectRefFromSupabaseUrl(url);
  if (ref !== STAGING_PROJECT_REF) {
    throw new Error(`Staging URL identifies project ${ref}`);
  }
  if (dryRun) {
    const { client, blocked } = createWriteBlockingClient(url, key);
    return { client: client as StagingClient, blocked, url, key };
  }
  return {
    client: createClient(url, key) as StagingClient,
    blocked: [],
    url,
    key,
  };
}

