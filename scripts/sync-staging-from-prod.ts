/** Staging rows in scope for a planned batch, for the dry-run diff. */
async function readExistingForDiff(
  client: StagingClient,
  table: CopyTable,
  rows: Row[],
): Promise<Row[]> {
  const column = DIFF_LOOKUP_COLUMN[table];
  const values = [
    ...new Set(
      rows
        .map((row) => row[column])
        .filter((value): value is string => typeof value === "string"),
    ),
  ];
  if (values.length === 0) return [];
  return readByValues<Row>(client, table, "*", column, values, [column]);
}

