type QueryResult = { data: unknown; error: unknown };

function describeError(error: unknown): string {
  if (isRecord(error) && typeof error.message === "string")
    return error.message;
  return String(error);
}

/**
 * Reads every row a query matches, one PostgREST page at a time.
 *
 * A single `.select()` silently stops at the server's max-rows ceiling, so a
 * table read without paging looks complete and is not. The loop stops at the
 * first short page.
 */
async function readAllPages<T>(
  build: (from: number, to: number) => PromiseLike<QueryResult>,
  label: string,
): Promise<T[]> {
  const collected: T[] = [];
  for (let offset = 0; ; offset += PAGE_SIZE) {
    const { data, error } = await build(offset, offset + PAGE_SIZE - 1);
    if (error) throw new Error(`${label} failed: ${describeError(error)}`);
    const page = (data ?? []) as T[];
    collected.push(...page);
    if (page.length < PAGE_SIZE) return collected;
  }
}

/** Paged read of a whole table. */
async function readTable<T>(
  client: ProdClient | StagingClient,
  table: string,
  columns: string,
  orderColumns: string[],
): Promise<T[]> {
  return readAllPages<T>((from, to) => {
    let query = client.from(table).select(columns);
    for (const column of orderColumns) query = query.order(column);
    return query.range(from, to);
  }, `read ${table}`);
}

/** Paged, chunked read of the rows matching a value list. */
async function readByValues<T>(
  client: ProdClient | StagingClient,
  table: string,
  columns: string,
  column: string,
  values: string[],
  orderColumns: string[],
): Promise<T[]> {
  const collected: T[] = [];
  for (const chunk of chunked(values)) {
    const page = await readAllPages<T>((from, to) => {
      let query = client.from(table).select(columns).in(column, chunk);
      for (const orderColumn of orderColumns) query = query.order(orderColumn);
      return query.range(from, to);
    }, `read ${table} by ${column}`);
    collected.push(...page);
  }
  return collected;
}

async function countRows(
  client: ProdClient | StagingClient,
  table: string,
): Promise<number> {
  const { count, error } = await client
    .from(table)
    .select("*", { count: "exact", head: true });
  if (error) throw new Error(`count ${table} failed: ${describeError(error)}`);
  return count ?? 0;
}

