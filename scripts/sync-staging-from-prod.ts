/**
 * The `seo_promoted` generated column, recomputed locally.
 *
 * Postgres owns the real value and this never writes it. It exists so the
 * selection can guarantee staging holds brands that fall BELOW the content
 * bar — the sitemap-exclusion and directory-ordering paths have no test data
 * otherwise. Mirrors 20260808150000_brand_seo_promotion_bar.sql exactly; if
 * that migration's formula changes, this must change with it.
 */
export function computeSeoPromoted(
  brand: Pick<
    SelectionCandidate,
    | "description"
    | "city"
    | "model_faq_count"
    | "purchase_website"
    | "purchase_pinkoi"
    | "purchase_shopee"
    | "purchase_myship"
  >,
): boolean {
  const hasChannel = [
    brand.purchase_website,
    brand.purchase_pinkoi,
    brand.purchase_shopee,
    brand.purchase_myship,
  ].some((value) => (value ?? "").trim().length > 0);
  return (
    (brand.description ?? "").length >= 200 &&
    hasChannel &&
    ((brand.city ?? "").trim().length > 0 || brand.model_faq_count >= 3)
  );
}

export function categorySlugKey(value: string | null): string {
  const trimmed = (value ?? "").trim();
  return trimmed.length > 0 ? trimmed : UNKNOWN_CATEGORY;
}

/** Coverage floors. Below these the corresponding page or query has no data. */
export const COVERAGE_FLOORS = {
  eventBrands: 10,
  redirectTargets: 5,
  seoPromotedFalse: 5,
  cityNull: 3,
  cityPresent: 3,
} as const;

/**
 * Picks the brands to copy. Pure and deterministic: same candidates plus same
 * seed always produce the same slugs, in the same order.
 *
 * Order of operations matters. Pinned brands come first because staging
 * already holds them and leaving one behind would leave a fixture stub sitting
 * next to fully populated neighbours. Coverage forcing comes second, before
 * any proportional filling, because the shapes it protects — a brand with zero
 * FAQ entries, a verified MIT brand, a redirect target — are rare enough that
 * a proportional draw reliably misses them. The quota fill gets whatever
 * budget is left, which is what keeps staging's category mix recognisably
 * production's.
 */
export function planBrandSelection(input: {
  candidates: SelectionCandidate[];
  pinnedSlugs: string[];
  target: number;
  seed: number;
}): SelectionPlan {
  const { candidates, pinnedSlugs, target, seed } = input;
  if (target < 1) throw new Error("Selection target must be at least 1");

  const bySlug = new Map(candidates.map((brand) => [brand.slug, brand]));
  const ordered = [...candidates].sort((a, b) =>
    selectionHash(seed, a.slug).localeCompare(selectionHash(seed, b.slug)),
  );

  const selected = new Map<string, SelectionCandidate>();
  const take = (brand: SelectionCandidate): void => {
    selected.set(brand.slug, brand);
  };

  // 1. Pinned — every brand staging already holds.
  const pinned: string[] = [];
  const pinnedMissingFromProduction: string[] = [];
  for (const slug of [...new Set(pinnedSlugs)].sort()) {
    const brand = bySlug.get(slug);
    if (!brand) {
      pinnedMissingFromProduction.push(slug);
      continue;
    }
    pinned.push(slug);
    take(brand);
  }

  // 2. Coverage floors, in descending order of scarcity.
  for (const brand of ordered) {
    if (brand.mit_status === "verified") take(brand);
  }

  const faqZeroTypes = new Set(
    [...selected.values()]
      .filter((brand) => brand.model_faq_count === 0)
      .map((brand) => categorySlugKey(brand.category)),
  );
  for (const brand of ordered) {
    if (brand.model_faq_count !== 0) continue;
    const type = categorySlugKey(brand.category);
    if (faqZeroTypes.has(type)) continue;
    faqZeroTypes.add(type);
    take(brand);
  }

  const fillFloor = (
    predicate: (brand: SelectionCandidate) => boolean,
    floor: number,
  ): void => {
    let have = [...selected.values()].filter(predicate).length;
    for (const brand of ordered) {
      if (have >= floor) return;
      if (!predicate(brand) || selected.has(brand.slug)) continue;
      take(brand);
      have += 1;
    }
  };

  fillFloor((brand) => brand.isEventBrand, COVERAGE_FLOORS.eventBrands);
  fillFloor((brand) => brand.isRedirectTarget, COVERAGE_FLOORS.redirectTargets);
  fillFloor(
    (brand) => !computeSeoPromoted(brand),
    COVERAGE_FLOORS.seoPromotedFalse,
  );
  // A null city and a present city travel different code paths on the detail
  // page and in the city facet, so staging needs both.
  fillFloor(
    (brand) => (brand.city ?? "").trim().length === 0,
    COVERAGE_FLOORS.cityNull,
  );
  fillFloor(
    (brand) => (brand.city ?? "").trim().length > 0,
    COVERAGE_FLOORS.cityPresent,
  );

  // 3. Proportional fill on production's own approved distribution, computed
  //    from the candidates rather than hard-coded: a frozen distribution rots
  //    the first time a category grows.
  const quotas = planCategoryQuotas(candidates, target);
  const remaining = ordered.filter((brand) => !selected.has(brand.slug));
  const byRichness = [...remaining].sort(compareRichness(seed));

  for (const [type, quota] of quotas) {
    let have = [...selected.values()].filter(
      (brand) => categorySlugKey(brand.category) === type,
    ).length;
    for (const brand of byRichness) {
      if (selected.size >= target) break;
      if (have >= quota) break;
      if (selected.has(brand.slug)) continue;
      if (categorySlugKey(brand.category) !== type) continue;
      take(brand);
      have += 1;
    }
  }

  // 4. Top-up. A category can run out of candidates before its quota is
  //    met; without this the run lands short of `target` for a reason nobody
  //    would think to look for.
  for (const brand of byRichness) {
    if (selected.size >= target) break;
    if (selected.has(brand.slug)) continue;
    take(brand);
  }

  const chosen = [...selected.values()];
  const byCategory: Record<string, number> = {};
  for (const brand of chosen) {
    const type = categorySlugKey(brand.category);
    byCategory[type] = (byCategory[type] ?? 0) + 1;
  }

  return {
    target,
    seed,
    // Sorted so the committed file has a reviewable diff: adding one brand
    // shows as one added line, not as a reshuffle.
    slugs: chosen.map((brand) => brand.slug).sort(),
    rationale: {
      byCategory: Object.fromEntries(
        Object.entries(byCategory).sort(([a], [b]) => a.localeCompare(b)),
      ),
      pinned,
      pinnedMissingFromProduction,
      coverage: {
        faqZero: chosen.filter((brand) => brand.model_faq_count === 0).length,
        mitVerified: chosen.filter((brand) => brand.mit_status === "verified")
          .length,
        eventBrands: chosen.filter((brand) => brand.isEventBrand).length,
        redirectTargets: chosen.filter((brand) => brand.isRedirectTarget)
          .length,
        seoPromotedFalse: chosen.filter((brand) => !computeSeoPromoted(brand))
          .length,
        cityNull: chosen.filter(
          (brand) => (brand.city ?? "").trim().length === 0,
        ).length,
        cityPresent: chosen.filter(
          (brand) => (brand.city ?? "").trim().length > 0,
        ).length,
      },
    },
  };
}

/**
 * Largest-remainder apportionment of `target` seats across category, on
 * the candidate distribution. Ties break on the type name so the result does
 * not depend on Postgres' row order.
 */
export function planCategoryQuotas(
  candidates: SelectionCandidate[],
  target: number,
): Map<string, number> {
  const counts = new Map<string, number>();
  for (const brand of candidates) {
    const type = categorySlugKey(brand.category);
    counts.set(type, (counts.get(type) ?? 0) + 1);
  }
  const total = candidates.length;
  if (total === 0) return new Map();

  const exact = [...counts.entries()].map(([type, count]) => ({
    type,
    share: (count * target) / total,
  }));
  const quotas = new Map(
    exact.map(({ type, share }) => [type, Math.floor(share)]),
  );
  let assigned = [...quotas.values()].reduce((sum, value) => sum + value, 0);

  const byRemainder = [...exact].sort((a, b) => {
    const remainderA = a.share - Math.floor(a.share);
    const remainderB = b.share - Math.floor(b.share);
    if (remainderA !== remainderB) return remainderB - remainderA;
    return a.type.localeCompare(b.type);
  });
  let cursor = 0;
  while (assigned < target && byRemainder.length > 0) {
    const entry = byRemainder[cursor % byRemainder.length];
    quotas.set(entry.type, (quotas.get(entry.type) ?? 0) + 1);
    assigned += 1;
    cursor += 1;
  }

  return new Map([...quotas.entries()].sort(([a], [b]) => a.localeCompare(b)));
}

/** Richest first: a brand with images and channels exercises more of the app. */
function compareRichness(
  seed: number,
): (a: SelectionCandidate, b: SelectionCandidate) => number {
  return (a, b) => {
    if (a.imageCount !== b.imageCount) return b.imageCount - a.imageCount;
    if (a.channelCount !== b.channelCount)
      return b.channelCount - a.channelCount;
    const lengthA = (a.description ?? "").length;
    const lengthB = (b.description ?? "").length;
    if (lengthA !== lengthB) return lengthB - lengthA;
    return selectionHash(seed, a.slug).localeCompare(
      selectionHash(seed, b.slug),
    );
  };
}

