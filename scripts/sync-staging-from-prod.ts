function assertKnownColumns(table: CopyTable, row: Row): void {
  const known = new Set(KNOWN_COLUMNS[table]);
  for (const column of Object.keys(row)) {
    if (known.has(column)) continue;
    throw new Error(
      `${table}.${column} exists in production but is not in KNOWN_COLUMNS. Decide whether it is safe to copy (a plain content column) or must be nulled (any FK into auth.users, any owner PII) and add it.`,
    );
  }
}

function applyPolicy(table: CopyTable, row: Row): Row {
  const policy = TABLE_POLICIES[table];
  const payload: Row = {};
  for (const [column, value] of Object.entries(row)) {
    if (policy.omit.includes(column)) continue;
    payload[column] = value;
  }
  // Written explicitly rather than deleted: on an update the column must be
  // overwritten with null, and an absent key leaves the previous value.
  for (const column of policy.nullify) payload[column] = null;
  return payload;
}

/**
 * Production `brands` rows to staging upsert payloads. See TABLE_POLICIES for
 * why each excluded column is excluded.
 */
export function planBrandRows(prodBrands: Row[]): Row[] {
  return prodBrands.map((row) => {
    assertKnownColumns("brands", row);
    return applyPolicy("brands", row);
  });
}

export type BrandRef = { id: string; slug: string };

export type BrandIdRemap = {
  map: Map<string, string>;
  /** Selected slugs with no staging row. Non-empty means the brands upsert
   * did not land, and every child write after this point would attach to
   * nothing. The caller throws. */
  missing: string[];
};

/**
 * Maps production brand ids to the staging ids the brands upsert produced.
 *
 * The slug-equality assertion is not defensive padding. A wrong entry here
 * attaches production brand A's photographs, channels and FAQ answers to
 * staging brand B; every page still renders, every query still succeeds, and
 * nothing anywhere reports an error. There is no later stage that can catch
 * it, so it is caught here or not at all.
 */
export function planBrandIdRemap(
  prodBrands: BrandRef[],
  stagingBrands: BrandRef[],
): BrandIdRemap {
  const stagingById = new Map<string, BrandRef>();
  const stagingBySlug = new Map<string, BrandRef>();
  for (const row of stagingBrands) {
    if (stagingBySlug.has(row.slug)) {
      throw new Error(`Staging returned two brands with slug "${row.slug}"`);
    }
    stagingBySlug.set(row.slug, row);
    stagingById.set(row.id, row);
  }

  const map = new Map<string, string>();
  const missing: string[] = [];
  for (const brand of prodBrands) {
    const target = stagingBySlug.get(brand.slug);
    if (!target) {
      missing.push(brand.slug);
      continue;
    }
    const confirmed = stagingById.get(target.id);
    if (!confirmed || confirmed.slug !== brand.slug) {
      throw new Error(
        `Brand id remap for "${brand.slug}" resolves to staging row ${target.id}, whose slug is "${confirmed?.slug ?? "missing"}"`,
      );
    }
    map.set(brand.id, target.id);
  }
  return { map, missing };
}

export type ChildRowPlan = {
  rows: Row[];
  /** Source brand ids with no remap entry. Reported so the run can fail with
   * the ids named, rather than writing a quietly short table. */
  unmapped: string[];
};

/**
 * Applies a child table's policy and rewrites its brand id. Tables with no
 * brand column (`events`, `event_exhibitors`) pass through the same path so
 * their nullify lists live in one place.
 */
export function planChildRows(
  table: CopyTable,
  rows: Row[],
  idMap: Map<string, string>,
): ChildRowPlan {
  const policy = TABLE_POLICIES[table];
  const planned: Row[] = [];
  const unmapped: string[] = [];

  for (const row of rows) {
    assertKnownColumns(table, row);
    const payload = applyPolicy(table, row);
    if (policy.brandIdColumn) {
      const sourceId = row[policy.brandIdColumn];
      const mapped =
        typeof sourceId === "string" ? idMap.get(sourceId) : undefined;
      if (!mapped) {
        unmapped.push(String(sourceId));
        continue;
      }
      payload[policy.brandIdColumn] = mapped;
    }
    planned.push(payload);
  }

  return { rows: planned, unmapped };
}

export type ImageUpsertPlan = {
  /** Upserted on (brand_id, source_url), production id dropped. */
  withSourceUrl: Row[];
  /** Upserted on id, production id preserved — see below. */
  withoutSourceUrl: Row[];
  unmapped: string[];
};

/**
 * Splits brand_images by whether it has a source_url.
 *
 * The unique index is (brand_id, source_url) and source_url is NULLABLE. NULL
 * never conflicts with NULL in a unique index, so a single natural-key upsert
 * inserts a fresh duplicate of every null-source row on every run and the
 * gallery grows without bound. Those rows conflict on `id` instead, which
 * means keeping production's id for them and only for them.
 *
 * `provider_metadata` is copied verbatim including nulls. The
 * brand_images_copy_provider_metadata BEFORE INSERT trigger tries to backfill
 * a null from `submission_images`, and staging has no matching submissions, so
 * whatever production holds is the only value staging will ever have.
 */
export function planImageUpserts(
  images: Row[],
  idMap: Map<string, string>,
): ImageUpsertPlan {
  const withSourceUrl: Row[] = [];
  const withoutSourceUrl: Row[] = [];
  const unmapped: string[] = [];

  for (const row of images) {
    assertKnownColumns("brand_images", row);
    const sourceBrandId = row.brand_id;
    const mapped =
      typeof sourceBrandId === "string" ? idMap.get(sourceBrandId) : undefined;
    if (!mapped) {
      unmapped.push(String(sourceBrandId));
      continue;
    }

    const hasSourceUrl =
      typeof row.source_url === "string" && row.source_url.length > 0;
    const payload = applyPolicy("brand_images", row);
    payload.brand_id = mapped;
    if (hasSourceUrl) {
      withSourceUrl.push(payload);
    } else {
      withoutSourceUrl.push({ ...payload, id: row.id });
    }
  }

  return { withSourceUrl, withoutSourceUrl, unmapped };
}

export type SlugRedirectPlan = {
  rows: Row[];
  /** Redirects whose old_slug is a live staging brand slug. Inserting one
   * would shadow a real staging brand behind a redirect to another. */
  skippedOldSlugs: string[];
};

export function planSlugRedirects(
  redirects: Row[],
  selectedSlugs: string[],
  stagingBrandSlugs: string[],
): SlugRedirectPlan {
  const selected = new Set(selectedSlugs);
  const live = new Set(stagingBrandSlugs);
  const rows: Row[] = [];
  const skippedOldSlugs: string[] = [];

  for (const row of redirects) {
    assertKnownColumns("brand_slug_redirects", row);
    const newSlug = row.new_slug;
    const oldSlug = row.old_slug;
    if (typeof newSlug !== "string" || !selected.has(newSlug)) continue;
    if (typeof oldSlug === "string" && live.has(oldSlug)) {
      skippedOldSlugs.push(oldSlug);
      continue;
    }
    rows.push(applyPolicy("brand_slug_redirects", row));
  }

  return { rows, skippedOldSlugs };
}

/**
 * `mit_registry` has no brand key at all. The only sound link is the cert
 * number a verified brand already stores in `mit_evidence.mit_smile_cert`,
 * which is what `verifyMitByCert` matches on. Fuzzy name matching would be the
 * obvious alternative and is deliberately not built: the table has no public
 * read path, so a wrong match buys nothing and a missing row costs nothing.
 */
export function planMitRegistryCerts(prodBrands: Row[]): string[] {
  const certs = new Set<string>();
  for (const brand of prodBrands) {
    const evidence = brand.mit_evidence;
    if (!isRecord(evidence)) continue;
    const cert = evidence.mit_smile_cert;
    if (typeof cert !== "string") continue;
    const trimmed = cert.trim();
    if (trimmed) certs.add(trimmed);
  }
  return [...certs].sort();
}

