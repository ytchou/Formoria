export type SelectArgs = { target: number; seed: number; dryRun: boolean };
export type SyncArgs = {
  dryRun: boolean;
  only: CopyTable[] | null;
  slugs: string[] | null;
};

function flagValue(argv: string[], name: string): string | undefined {
  const inline = argv.find((arg) => arg.startsWith(`${name}=`));
  if (inline) return inline.slice(name.length + 1);
  const index = argv.indexOf(name);
  return index >= 0 ? argv[index + 1] : undefined;
}

export function parseSelectArgs(argv: string[]): SelectArgs {
  const target = Number(flagValue(argv, "--target") ?? 100);
  const seed = Number(flagValue(argv, "--seed") ?? 1);
  if (!Number.isInteger(target) || target < 1) {
    throw new Error("--target must be a positive integer");
  }
  if (!Number.isInteger(seed)) throw new Error("--seed must be an integer");
  return { target, seed, dryRun: argv.includes("--dry-run") };
}

export function parseSyncArgs(argv: string[]): SyncArgs {
  const onlyRaw = flagValue(argv, "--only");
  let only: CopyTable[] | null = null;
  if (onlyRaw !== undefined) {
    const names = onlyRaw
      .split(",")
      .map((name) => name.trim())
      .filter(Boolean);
    if (names.length === 0) throw new Error("--only requires a table list");
    for (const name of names) {
      if (!(COPY_ORDER as readonly string[]).includes(name)) {
        throw new Error(
          `--only names unknown table "${name}"; expected one of ${COPY_ORDER.join(", ")}`,
        );
      }
    }
    only = names as CopyTable[];
  }

  const slugs = argv.flatMap((arg, index) =>
    arg === "--slug" && argv[index + 1] ? [argv[index + 1]] : [],
  );

  return {
    dryRun: argv.includes("--dry-run"),
    only,
    slugs: slugs.length > 0 ? slugs : null,
  };
}

