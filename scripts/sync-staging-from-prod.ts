function isRecord(value: unknown): value is Row {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/**
 * supabase-js serializes `.in()` into the query string. Fifty uuids is already
 * a ~1.9KB request URI; a few hundred produces a bare HTTP 414 from the
 * fronting proxy with no PostgREST error body at all.
 */
export const IN_CHUNK_SIZE = 50;

/** PostgREST's own hard ceiling on a single response. */
export const PAGE_SIZE = 1000;

export function chunked<T>(values: T[], size = IN_CHUNK_SIZE): T[][] {
  const chunks: T[][] = [];
  for (let index = 0; index < values.length; index += size) {
    chunks.push(values.slice(index, index + size));
  }
  return chunks;
}

/** Stable, seed-dependent ordering key. Never `Math.random`: a selection that
 * changes between runs cannot be reviewed, and hashing rather than sorting by
 * slug keeps the pick from clustering on the alphabet. */
export function selectionHash(seed: number, slug: string): string {
  return createHash("sha256").update(`${seed}:${slug}`).digest("hex");
}

