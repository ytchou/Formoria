/**
 * Copies a curated subset of production content into the staging project.
 *
 * Staging is seeded from `supabase/fixtures/staging.sql` with brand rows that
 * have a name, a slug and a placeholder description and nothing else: no
 * images, no real purchase channels, no event participation, no FAQ entries. A
 * staging environment in that state cannot exercise galleries, /where-to-buy,
 * the event sections, or the FAQ/JSON-LD surfaces at all, so a regression in
 * any of them is invisible until production.
 *
 * Two subcommands:
 *
 *   pnpm db:sync:staging:select   choose ~100 production brands and write the
 *                                selection to scripts/sync-staging/brand-slugs.json
 *   pnpm db:sync:staging          copy those brands and their content into staging
 *
 * The selection is committed rather than recomputed on every sync: a reviewer
 * can see which brands staging holds without running anything, and two runs a
 * month apart copy the same brands instead of silently drifting.
 *
 * ---------------------------------------------------------------------------
 * Safety model
 * ---------------------------------------------------------------------------
 *
 * This is the only script in the repo that holds a live handle on BOTH
 * projects at once, so "which client am I holding" is the failure that matters
 * and it is answered three separate ways:
 *
 *   1. Credentials come from `supabase projects api-keys --project-ref <ref>`,
 *      never from the environment. `.env.local` holds PRODUCTION under the
 *      generic names, so a script that read the environment would have
 *      production as its default target — exactly backwards. The package.json
 *      entries deliberately omit `--env-file`; do not add it.
 *   2. Every key is put through `validateSupabaseKeyIdentity`, which decodes
 *      the JWT and asserts the key claims the project it was fetched for. A
 *      client can only be built from a key that names its own project.
 *   3. The production client is wrapped in `createWriteBlockingClient`, so a
 *      write to production is structurally impossible rather than merely
 *      unwritten. A non-empty blocked tally at exit fails the run: it means a
 *      code path tried, and the next reader must know.
 *
 * The client types are branded so that passing the production client to a
 * write helper is a compile error, not a runtime surprise.
 *
 * The sync is ADDITIVE. There is no delete anywhere in this file, and there
 * are exactly two write calls: `upsertBatch` for rows and the storage upload
 * in `syncStorageObjects` for the bytes those rows point at.
 * `curated_products` is deliberately untouched — production has zero rows, and
 * staging's rows are the real authored supply, not a fixture (DEV-1485 deleted the synthetic one), so any
 * mirroring of that table would destroy the homepage product wall's only data.
 *
 * There is no seed ordering to respect any more: `db:seed:staging` no longer
 * writes curated products at all. If the wall's supply ever reaches zero,
 * `e2e/utils/wall-supply.ts` now counts it live and skips rather than failing —
 * that count, not this script, is where a missing wall gets diagnosed.
 */
