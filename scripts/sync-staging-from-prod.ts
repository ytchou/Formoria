async function runSync(argv: string[]): Promise<void> {
  const args = parseSyncArgs(argv);
  const production = createProductionClient();
  const staging = createStagingClient(args.dryRun);

  const wants = (table: CopyTable): boolean =>
    args.only === null || args.only.includes(table);

  console.log(
    `${args.dryRun ? "[dry-run] " : ""}Syncing ${PRODUCTION_PROJECT_REF} -> ${STAGING_PROJECT_REF}`,
  );

  // --- Selection -----------------------------------------------------------
  const selectionRaw = JSON.parse(
    await readFile(SELECTION_FILE, "utf8"),
  ) as unknown;
  let slugs = parseSelectionFile(selectionRaw);
  if (args.slugs) {
    const requested = new Set(args.slugs);
    const unknown = args.slugs.filter((slug) => !slugs.includes(slug));
    if (unknown.length > 0) {
      throw new Error(
        `--slug names ${unknown.join(", ")}, which the selection file does not list`,
      );
    }
    slugs = slugs.filter((slug) => requested.has(slug));
  }
  console.log(`Selection: ${slugs.length} brands`);

  // --- Preflight -----------------------------------------------------------
  const prodColumns = await fetchOpenApiColumns(
    production.url,
    production.key,
    "production",
  );
  const stagingColumns = await fetchOpenApiColumns(
    staging.url,
    staging.key,
    "staging",
  );
  const drift = planColumnDrift(prodColumns, stagingColumns, COPY_ORDER);
  if (drift.length > 0) {
    for (const entry of drift) {
      console.error(
        `Schema drift: staging.${entry.table} is missing ${entry.columns.join(", ")}`,
      );
    }
    throw new Error(
      "Staging schema is behind production. Run `pnpm db:migrate` against staging first.",
    );
  }

  // The same comparison against KNOWN_COLUMNS. The row planners reject an
  // unknown column too, but they do so table by table, so without this the run
  // would already have written `events` and `brands` before discovering that a
  // new `brand_images` column needs a decision. Here it costs nothing.
  const unknownColumns = planColumnDrift(
    prodColumns,
    new Map<string, Set<string>>(
      COPY_ORDER.map((table): [string, Set<string>] => [
        table,
        new Set(KNOWN_COLUMNS[table]),
      ]),
    ),
    COPY_ORDER,
  );
  if (unknownColumns.length > 0) {
    for (const entry of unknownColumns) {
      console.error(
        `Unmapped production column(s) on ${entry.table}: ${entry.columns.join(", ")}`,
      );
    }
    throw new Error(
      "Production has columns this sync has never been told about. Add each to KNOWN_COLUMNS, and to a nullify list if it is an auth.users reference or owner PII.",
    );
  }

  const before = new Map<string, number>();
  for (const table of COUNTED_TABLES) {
    before.set(table, await countRows(staging.client, table));
  }
  console.log(
    `Staging before: ${COUNTED_TABLES.map((table) => `${table}=${before.get(table)}`).join(" ")}`,
  );

  // A selected brand still carrying the fixture description means the fixture
  // ran after the last sync and overwrote the copied content. It is a warning
  // rather than a refusal because this sync is the repair: refusing would make
  // the stated remedy impossible, and on a first run every fixture brand is in
  // exactly this state.
  const stagingSelected = await readByValues<Row>(
    staging.client,
    "brands",
    "slug,description",
    "slug",
    slugs,
    ["slug"],
  );
  const fixtureStubs = stagingSelected.filter(
    (row) => row.description === FIXTURE_DESCRIPTION,
  );
  if (fixtureStubs.length > 0) {
    console.warn(
      `${fixtureStubs.length} selected brand(s) still hold the staging fixture description; this run replaces it. If that count grows after a sync, db:seed:staging ran last — re-run this sync.`,
    );
  }

  // --- Read production -----------------------------------------------------
  const prodBrands = await readByValues<Row>(
    production.client,
    "brands",
    "*",
    "slug",
    slugs,
    ["slug"],
  );
  const foundSlugs = new Set(prodBrands.map((row) => String(row.slug)));
  const missingInProduction = slugs.filter((slug) => !foundSlugs.has(slug));
  if (missingInProduction.length > 0) {
    throw new Error(
      `Production has no brand for ${missingInProduction.join(", ")}. Re-run db:sync:staging:select.`,
    );
  }
  const prodBrandIds = prodBrands.map((row) => String(row.id));

  const prodEventBrands = await readByValues<Row>(
    production.client,
    "event_brands",
    "*",
    "brand_id",
    prodBrandIds,
    ["id"],
  );
  const eventIds = [
    ...new Set(prodEventBrands.map((row) => String(row.event_id))),
  ];
  const prodEvents =
    eventIds.length > 0
      ? await readByValues<Row>(
          production.client,
          "events",
          "*",
          "id",
          eventIds,
          ["id"],
        )
      : [];
  // Every exhibitor of a referenced event, not only the linked ones:
  // event_brands.event_exhibitor_id can point at any of them, and the floor
  // map renders the unlinked rows too.
  const prodExhibitors =
    eventIds.length > 0
      ? await readByValues<Row>(
          production.client,
          "event_exhibitors",
          "*",
          "event_id",
          eventIds,
          ["id"],
        )
      : [];

  // A staging event that shares a slug with a production event but has a
  // different id would fail the events upsert on the slug unique index, after
  // the conflict target (id) has already missed it.
  const stagingEvents = await readTable<{ id: string; slug: string }>(
    staging.client,
    "events",
    "id,slug",
    ["id"],
  );
  const stagingEventIdBySlug = new Map(
    stagingEvents.map((row) => [row.slug, row.id]),
  );
  for (const event of prodEvents) {
    const existingId = stagingEventIdBySlug.get(String(event.slug));
    if (existingId && existingId !== String(event.id)) {
      throw new Error(
        `Staging already has an event "${String(event.slug)}" under a different id (${existingId}). Resolve it by hand before syncing.`,
      );
    }
  }

  const prodImages = await readByValues<Row>(
    production.client,
    "brand_images",
    "*",
    "brand_id",
    prodBrandIds,
    ["id"],
  );
  const prodFaq = await readByValues<Row>(
    production.client,
    "brand_faq_entries",
    "*",
    "brand_id",
    prodBrandIds,
    ["brand_id", "preset_id", "position"],
  );
  const prodChannels = await readByValues<Row>(
    production.client,
    "brand_channels",
    "*",
    "brand_id",
    prodBrandIds,
    ["id"],
  );
  const prodRedirects = await readByValues<Row>(
    production.client,
    "brand_slug_redirects",
    "*",
    "new_slug",
    slugs,
    ["old_slug"],
  );
  const certs = planMitRegistryCerts(prodBrands);
  const prodRegistry =
    certs.length > 0
      ? await readByValues<Row>(
          production.client,
          "mit_registry",
          "*",
          "cert_number",
          certs,
          ["cert_number"],
        )
      : [];

  const copied = new Map<string, number>();
  const planned = new Map<string, number>();
  /** Every planned batch, keyed by table + conflict target. brand_images
   * appears twice (see planImageUpserts) and each partition diffs separately. */
  const plannedBatches: {
    table: CopyTable;
    onConflict: string;
    rows: Row[];
  }[] = [];

  const write = async (
    table: CopyTable,
    rows: Row[],
    onConflict = TABLE_POLICIES[table].onConflict,
  ): Promise<void> => {
    planned.set(table, (planned.get(table) ?? 0) + rows.length);
    plannedBatches.push({ table, onConflict, rows });
    if (rows.length === 0) return;
    const written = await upsertBatch(
      staging.client,
      table,
      rows,
      onConflict,
      TABLE_POLICIES[table].batchSize,
    );
    copied.set(table, (copied.get(table) ?? 0) + written);
  };

  // --- 1-2. Events and exhibitors -----------------------------------------
  if (wants("events")) {
    await write("events", planChildRows("events", prodEvents, new Map()).rows);
  }
  if (wants("event_exhibitors")) {
    await write(
      "event_exhibitors",
      planChildRows("event_exhibitors", prodExhibitors, new Map()).rows,
    );
  }

  // --- 3. Brands -----------------------------------------------------------
  if (wants("brands")) {
    await write("brands", planBrandRows(prodBrands));
  }

  // --- 4. Remap ------------------------------------------------------------
  const stagingBrandRefs = await readByValues<BrandRef>(
    staging.client,
    "brands",
    "id,slug",
    "slug",
    slugs,
    ["slug"],
  );
  const remap = planBrandIdRemap(
    prodBrands.map((row) => ({ id: String(row.id), slug: String(row.slug) })),
    stagingBrandRefs,
  );
  if (remap.missing.length > 0) {
    if (!args.dryRun) {
      throw new Error(
        `${remap.missing.length} selected brand(s) are absent from staging after the brands upsert: ${remap.missing.slice(0, 10).join(", ")}`,
      );
    }
    // A dry run never inserted them, so they cannot be there. Placeholders let
    // the child planners run and report their real row counts.
    console.log(
      `[dry-run] ${remap.missing.length} brand(s) would be created in staging`,
    );
    remap.missing.forEach((slug, index) => {
      const brand = prodBrands.find((row) => String(row.slug) === slug);
      if (brand) remap.map.set(String(brand.id), dryRunPlaceholderId(index));
    });
  }

  // --- 5-8. Brand-keyed children ------------------------------------------
  if (wants("brand_images")) {
    const imagePlan = planImageUpserts(prodImages, remap.map);
    assertMapped("brand_images", imagePlan.unmapped);
    await write("brand_images", imagePlan.withSourceUrl);
    // Null source_url never conflicts with null in a unique index, so these
    // rows go through their primary key instead — see planImageUpserts.
    await write("brand_images", imagePlan.withoutSourceUrl, "id");
  }
  if (wants("brand_faq_entries")) {
    const plan = planChildRows("brand_faq_entries", prodFaq, remap.map);
    assertMapped("brand_faq_entries", plan.unmapped);
    await write("brand_faq_entries", plan.rows);
  }
  if (wants("brand_channels")) {
    const plan = planChildRows("brand_channels", prodChannels, remap.map);
    assertMapped("brand_channels", plan.unmapped);
    await write("brand_channels", plan.rows);
  }
  if (wants("event_brands")) {
    const plan = planChildRows("event_brands", prodEventBrands, remap.map);
    assertMapped("event_brands", plan.unmapped);
    await write("event_brands", plan.rows);
  }

  // --- 9. Slug redirects ---------------------------------------------------
  if (wants("brand_slug_redirects")) {
    const oldSlugs = prodRedirects.map((row) => String(row.old_slug));
    const liveStagingSlugs =
      oldSlugs.length > 0
        ? (
            await readByValues<{ slug: string }>(
              staging.client,
              "brands",
              "slug",
              "slug",
              oldSlugs,
              ["slug"],
            )
          ).map((row) => row.slug)
        : [];
    const plan = planSlugRedirects(prodRedirects, slugs, liveStagingSlugs);
    if (plan.skippedOldSlugs.length > 0) {
      console.warn(
        `Skipped ${plan.skippedOldSlugs.length} redirect(s) whose old_slug is a live staging brand: ${plan.skippedOldSlugs.join(", ")}`,
      );
    }
    await write("brand_slug_redirects", plan.rows);
  }

  // --- 10. MIT registry ----------------------------------------------------
  if (wants("mit_registry")) {
    await write(
      "mit_registry",
      prodRegistry.map((row) => {
        assertKnownColumns("mit_registry", row);
        return applyPolicy("mit_registry", row);
      }),
    );
  }

  // --- 11. Storage objects -------------------------------------------------
  // Gated on brand_images: it holds all but a handful of the referenced keys,
  // and `brands.hero_image_storage_path` is a denormalized copy of one of its
  // rows rather than an independent object.
  let storage: StorageCopyReport | null = null;
  if (wants("brand_images")) {
    const keyPlan = planStorageKeys({
      brands: prodBrands,
      brand_images: prodImages,
      events: prodEvents,
      event_exhibitors: prodExhibitors,
    });
    if (keyPlan.skippedByPrefix.length > 0) {
      const prefixes = tally(
        keyPlan.skippedByPrefix.map((key) => `${key.split("/").at(0) ?? key}/`),
      );
      console.log(
        `Storage: not copying ${keyPlan.skippedByPrefix.length} key(s) outside ${SYNCED_STORAGE_PREFIXES.join(", ")} (${[
          ...prefixes,
        ]
          .map(([prefix, count]) => `${prefix}=${count}`)
          .join(" ")})`,
      );
    }
    storage = await syncStorageObjects({
      production: production.client,
      staging: staging.client,
      keys: keyPlan.keys,
      dryRun: args.dryRun,
    });
    console.log(
      args.dryRun
        ? `[dry-run] storage: would copy ${storage.planned - storage.skippedPresent} object(s), ${storage.skippedPresent} already present`
        : `  storage: ${storage.copied} copied, ${storage.skippedPresent} already present, ${storage.failed} failed, ${storage.rejectedByBucket} refused by bucket mime policy (of ${storage.planned})`,
    );
    for (const message of storage.errors) console.error(`    ${message}`);
  }

  // --- Report --------------------------------------------------------------
  if (args.dryRun) {
    console.log("\n[dry-run] planned writes:");
    for (const batch of plannedBatches) {
      if (batch.rows.length === 0) continue;
      const existing = await readExistingForDiff(
        staging.client,
        batch.table,
        batch.rows,
      );
      const diff = planWriteDiff(
        batch.rows,
        existing,
        batch.onConflict.split(","),
      );
      console.log(
        `  ${batch.table} (on ${batch.onConflict}): insert ${diff.wouldInsert}, update ${diff.wouldUpdate}, unchanged ${diff.unchanged}`,
      );
    }
    console.log(
      `\n[dry-run] staging writes blocked: ${staging.blocked.length}. Nothing was written.`,
    );
    assertNoProductionWrites(production.blocked);
    printRunNotes();
    return;
  }

  for (const table of planCopyOrder()) {
    const plannedRows = planned.get(table) ?? 0;
    const copiedRows = copied.get(table) ?? 0;
    if (plannedRows === 0 && copiedRows === 0) continue;
    console.log(`  ${table}: ${copiedRows}/${plannedRows} row(s)`);
    if (copiedRows !== plannedRows) {
      throw new Error(
        `${table}: copied ${copiedRows} of ${plannedRows} planned rows`,
      );
    }
  }

  await assertPostConditions({
    staging: staging.client,
    production,
    slugs,
    before,
    remap: remap.map,
    checkImages: wants("brand_images"),
    checkFaq: wants("brand_faq_entries"),
  });

  printRunNotes();

  // Last, so the row report and the run notes are on screen first: a storage
  // failure is repaired by re-running this same command, and the operator
  // needs to see what did land before being told to run it again.
  if (storage && storage.failed > 0) {
    throw new Error(
      `${storage.failed} of ${storage.planned} storage object(s) did not copy. The stage is idempotent — re-run \`pnpm db:sync:staging\` to retry only the missing ones.`,
    );
  }
}

function assertMapped(table: string, unmapped: string[]): void {
  if (unmapped.length === 0) return;
  throw new Error(
    `${table}: ${unmapped.length} row(s) reference production brand ids with no staging counterpart (${[...new Set(unmapped)].slice(0, 5).join(", ")})`,
  );
}

async function assertPostConditions(input: {
  staging: StagingClient;
  production: { blocked: BlockedWrite[] };
  slugs: string[];
  before: Map<string, number>;
  remap: Map<string, string>;
  checkImages: boolean;
  checkFaq: boolean;
}): Promise<void> {
  const { staging, production, slugs, before, remap } = input;

  assertNoProductionWrites(production.blocked);

  const brands = await readByValues<Row>(
    staging,
    "brands",
    "id,slug,status,description,model_faq_count",
    "slug",
    slugs,
    ["slug"],
  );
  const bySlug = new Map(brands.map((row) => [String(row.slug), row]));
  for (const slug of slugs) {
    const brand = bySlug.get(slug);
    if (!brand)
      throw new Error(`Post-condition: ${slug} is missing in staging`);
    if (brand.status !== "approved") {
      throw new Error(
        `Post-condition: ${slug} has status ${String(brand.status)}, expected approved`,
      );
    }
    if (brand.description === FIXTURE_DESCRIPTION) {
      throw new Error(
        `Post-condition: ${slug} still holds the staging fixture description. Re-run db:seed:staging before this sync, not after.`,
      );
    }
  }

  for (const table of COUNTED_TABLES) {
    const after = await countRows(staging, table);
    const previous = before.get(table) ?? 0;
    if (after < previous) {
      throw new Error(
        `Post-condition: staging ${table} fell from ${previous} to ${after}. This sync is additive; something deleted rows.`,
      );
    }
  }

  const stagingIds = [...remap.values()];
  if (input.checkImages) {
    const images = await readByValues<{ brand_id: string }>(
      staging,
      "brand_images",
      "brand_id",
      "brand_id",
      stagingIds,
      ["brand_id"],
    );
    const counts = tally(images.map((row) => row.brand_id));
    const empty = brands.filter(
      (row) => (counts.get(String(row.id)) ?? 0) === 0,
    );
    if (empty.length > 0) {
      throw new Error(
        `Post-condition: ${empty.length} brand(s) have no images in staging (${empty
          .slice(0, 5)
          .map((row) => String(row.slug))
          .join(", ")})`,
      );
    }
  }

  if (input.checkFaq) {
    const faq = await readByValues<{ brand_id: string }>(
      staging,
      "brand_faq_entries",
      "brand_id",
      "brand_id",
      stagingIds,
      ["brand_id"],
    );
    const counts = tally(faq.map((row) => row.brand_id));
    for (const brand of brands) {
      const expected = counts.get(String(brand.id)) ?? 0;
      if (Number(brand.model_faq_count ?? 0) !== expected) {
        throw new Error(
          `Post-condition: ${String(brand.slug)} reports model_faq_count ${String(brand.model_faq_count)} but holds ${expected} FAQ entries. The sync_brand_model_faq_count trigger did not fire.`,
        );
      }
    }
  }
}

function printRunNotes(): void {
  console.log(
    [
      "",
      "Run order: `pnpm db:seed:staging` FIRST, then `pnpm db:sync:staging`.",
      "The reverse order lets the fixture overwrite copied brand content with",
      "its placeholder description.",
      "",
      "Images render through the same-origin /i/ proxy, which reads THIS",
      "project's own bucket (DEV-1551). The sync therefore copies the objects",
      "too, under `brands/` AND `submissions/`. Copying the bytes is not enough",
      "on its own: the proxy deny-lists a `submissions/` key whether the bytes",
      "are there or not, so run",
      "`pnpm tsx scripts/promote-submission-images.ts promote --live` against",
      "STAGING afterwards to rewrite those rows to `brands/` keys. Promotion is",
      "a server-side copy inside one bucket, which is why it needs the source",
      "bytes here first. Verify with `pnpm check:image-resolvability`.",
      "",
      "Re-run this sync to repair a gallery with missing bytes; it copies only",
      "what staging lacks. `event-exhibitors/` and `events/` keys are NOT",
      "copied — those surfaces stay image-blind on staging.",
    ].join("\n"),
  );
}

// ---------------------------------------------------------------------------
