/**
 * Deliberately NOT `isValidSlug` from src/lib/services/brands.ts.
 *
 * That one is a write-path validator: it constrains slugs `submissions.ts` is
 * about to mint, so it demands ASCII kebab-case. These slugs are read back out
 * of production, where 45 of 795 approved brands carry Han characters
 * (`廣源良-mit`, `新北坪林阿純茶園`) from an earlier import path. Validating live
 * data against the generator's rules rejects rows the site serves today.
 *
 * So this checks for a slug that is safe to put in a URL segment and in a
 * PostgREST filter — no whitespace, no separators, no control characters,
 * bounded length — and nothing about the alphabet.
 */
const UNSAFE_SLUG_CHARS = /[\s/\\?#&=%+.,;:'\"<>()[\]{}|^`~!*$@]/;
const CONTROL_CHARS = /[\u0000-\u001f\u007f]/;
const MAX_SLUG_LENGTH = 80;

/** Hyphens are legal and common in these slugs; the characters above are not. */
export function isSafeSelectionSlug(value: string): boolean {
  return (
    value.length > 0 &&
    value.length <= MAX_SLUG_LENGTH &&
    !UNSAFE_SLUG_CHARS.test(value) &&
    !CONTROL_CHARS.test(value) &&
    !value.startsWith("-") &&
    !value.endsWith("-")
  );
}

/**
 * Validates the committed selection. `slugs` is the ONLY field `sync` reads;
 * `rationale` exists for the reviewer. A malformed file must fail here rather
 * than reaching the database as a query for a slug that cannot exist.
 */
export function parseSelectionFile(raw: unknown): string[] {
  if (!isRecord(raw)) {
    throw new Error("Selection file must contain a JSON object");
  }
  const slugs = raw.slugs;
  if (!Array.isArray(slugs)) {
    throw new Error("Selection file must contain a slugs array");
  }
  if (slugs.length === 0) {
    throw new Error(
      "Selection file lists no slugs; run `pnpm db:sync:staging:select` first",
    );
  }
  const seen = new Set<string>();
  for (const value of slugs) {
    if (typeof value !== "string" || !isSafeSelectionSlug(value)) {
      throw new Error(
        `Selection file slug ${JSON.stringify(value)} is not URL-safe`,
      );
    }
    if (seen.has(value)) {
      throw new Error(`Selection file lists "${value}" more than once`);
    }
    seen.add(value);
  }
  return slugs as string[];
}

